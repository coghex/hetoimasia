-- | The shader compiler this package trusts, and how a shader reaches it.
--
-- D-11 keeps Synarchy's workflow — GLSL compiled while the Haskell build runs,
-- the SPIR-V embedded in the program — and P-9 requires that the compiler be
-- the pinned one and that a change to it rebuild what it compiled. GHC does
-- not notice an executable changing merely because a splice once ran it, and
-- Cabal does not notice a file a splice depends on unless the package lists
-- it. So the compiler's identity is written into a file before every build,
-- the /fingerprint/, which every splice registers as a dependency and which
-- the package's @**/*.fingerprint@ source glob makes Cabal watch.
--
-- The fingerprint is generated by @hetoimasia-shader-fingerprint@, this
-- package's own executable, from the private-prefix @glslangValidator@ wrapper
-- VK-4 provisions and the native manifest that records it. It carries:
--
-- * the target environment and the compiler flags, from 'configuredTarget'
--   and 'compilerFlags' below — the one place either is declared;
-- * the wrapper, by path and digest;
-- * the compiler the wrapper runs, by version, path and digest;
-- * the native manifest, by path and by the identity @native.py@ gives it:
--   the SHA-256 of the file.
--
-- Nothing here trusts a fingerprint it was handed. 'loadToolchain' reads one
-- and observes the live wrapper, compiler and manifest again, and refuses
-- unless they are what it records; the generator observes the same way and
-- refuses unless the wrapper, the compiler and the manifest agree with each
-- other. The wrapper is only ever found through the fingerprint or through
-- @HETOIMASIA_GLSLANG@, which @tools/native/native.py prepare@ exports. @PATH@
-- is never searched for a compiler, and the compiler runs with a @PATH@ this
-- module decides: the wrapper's own directory ahead of @\/usr\/bin:\/bin@, which
-- is where its @#!\/usr\/bin\/env bash@ line finds its shell.
--
-- The compile itself needs no display, device, loader or consent: it is a
-- child process that reads source text and writes SPIR-V. 'compileShader' is
-- the entry the Template Haskell adapter in
-- "Hetoimasia.GPU.Vulkan.Native.Shader" calls, and it is callable at run time
-- too, which is how its diagnostics are tested.
