-- | A point @(x, y, z)@ in the cell's local frame.
type P = (Rational, Rational, Rational)

-- | One expected face: a label (@Top@, @WallN@, @WallE@, @WallS@, @WallW@ or
-- @Bottom@) and its corners, in no particular order.
data FaceFixture = FaceFixture
  { fixtureFace ∷ String
  , fixtureCorners ∷ [P]
  }

-- | One shape's expected vertices and faces.
data ShapeFixture = ShapeFixture
  { fixtureId ∷ Int
  , fixtureVertices ∷ [P]
  , fixtureFaces ∷ [FaceFixture]
  }

