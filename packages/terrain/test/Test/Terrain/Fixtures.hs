-- | The top height of an identity at a footprint point, from the mask bits (1
-- North, 2 East, 4 South, 8 West): 1 for identity 0, and otherwise the minimum of
-- @y@, @1 - x@, @1 - y@ and @x@ over the bits that are set.
topHeight ∷ Int → Rational → Rational → Rational
topHeight identity x y =
  minimum (1 : [ramp | (bit, ramp) ← [(1, y), (2, 1 - x), (4, 1 - y), (8, x)], identity `div` bit `mod` 2 == 1])

