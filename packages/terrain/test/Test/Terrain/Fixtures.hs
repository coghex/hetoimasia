-- | Independently authored expected values for the terrain contracts.
--
-- Nothing here is produced by the code under test. Provenance of every table:
--
-- * 'shapeFixtures' is derived by hand from the contract in the package README
--   (the approved catalog, D-49 and P-9): the cell is @[0,1]³@ with X east, Y
--   south and Z up, and the solid of a shape is @0 <= z <= h(x, y)@ over the
--   unit footprint, where @h = 1@ for identity 0 and otherwise @h@ is the
--   minimum of the expressions named by the set bits (North @y@, East @1 - x@,
--   South @1 - y@, West @x@). Identity 15 therefore takes all four: a central
--   peak at @(1/2, 1/2, 1/2)@ over a full base, with no wall of positive area.
--   The vertex and face lists were solved on paper, one shape at a time, and
--   cross-checked by rotating the four-bit family by hand
--   ('fixtureConsistentUnderRotation' in "Test.Terrain.Geometry" re-checks that,
--   with the tests' own rotation).
--
-- * 'topHeight' is the same height rule stated as a function of the mask bits,
--   and 'openingAreaTable' the area of the empty space the solid leaves open on
--   each cell face, worked out on paper as @1@ less the wall area on a side, the
--   whole footprint on top of every identity but 0, and nothing on the bottom.
--
-- * 'rotationTable' and 'viewTable' were generated by a throwaway Python
--   script written for this issue, from the reference's own arithmetic:
--   a set bit @i@ (N, E, S, W is 0, 1, 2, 3) moves to bit @(i + t) mod 4@ for
--   a positive turn, and the reference's @viewSlopeId@
--   (@((bits >> t) | (bits << (4 - t))) & 15@ with t = 0, 1, 2, 3 for the South,
--   West, North and East facings, Synarchy
--   @3777d437ea00e1302bf55162ad5693fee4879187@,
--   @src/World/Render/Textures.hs:27-37@). Neither table is read from, or
--   written by, the library. No Synarchy checkout, PNG or other asset is read
--   by this suite or by the library; the figures above are the whole of what
--   was taken from the reference.
