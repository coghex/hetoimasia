-- | The texel as a decoded colour image stores it: colour channels premultiplied by alpha in linear light, rounded to
-- nearest, alpha unchanged (alpha 0 and 255 leave the channel as it is or zero). Worked out here from the transfer
-- function, not read from the decoder.
premultipliedTexel ∷ Texel → Texel
premultipliedTexel (r, g, b, a) = (channel r, channel g, channel b, a)
  where
    channel c
      | a == 255 = c
      | a == 0 = 0
      | otherwise = fromIntegral (min 255 (floor (encode (decode (fromIntegral c / 255) * fromIntegral a / 255) * 255 + 0.5) ∷ Int))

-- | The fixture as the oracle reads a texture: level 0 only (every case magnifies), 'TexelRgba8Srgb', premultiplied.
fixtureDecoded ∷ Fixture → DecodedImage
fixtureDecoded fixture =
  DecodedImage
    { decodedFormat = TexelRgba8Srgb
    , decodedWidth = fromIntegral (fixtureWidth fixture)
    , decodedHeight = fromIntegral (fixtureHeight fixture)
    , decodedLevels = [ByteString.pack (concat [[r, g, b, a] | y ← [0 .. fixtureHeight fixture - 1], x ← [0 .. fixtureWidth fixture - 1], let (r, g, b, a) = premultipliedTexel (fixtureTexel fixture x y)])]
    , decodedBinaryAlpha = and [a == 0 || a == 255 | y ← [0 .. fixtureHeight fixture - 1], x ← [0 .. fixtureWidth fixture - 1], let (_, _, _, a) = fixtureTexel fixture x y]
    }

-- | The SHA-256 of some bytes, in lower-case hexadecimal.
sha256Text ∷ ByteString → Text
sha256Text bytes = Text.pack (concatMap two (ByteString.unpack (hash bytes)))
  where
    two byte = (if byte < 16 then "0" else "") <> showHex byte ""

-- | A path, found by looking for it under the working directory and then under each directory above it: the suites run
-- from the repository root (the runner) or from a package directory (@cabal test@).
findUpwards ∷ FilePath → IO FilePath
findUpwards relative = getCurrentDirectory >>= go
  where
    go directory = do
      found ← doesPathExist (directory </> relative)
      if found
        then pure (directory </> relative)
        else
          let parent = takeDirectory directory
           in if parent == directory then ioError (userError ("not found above the working directory: " <> relative)) else go parent

-- | The sRGB transfer function's decoding direction (IEC 61966-2-1), encoded to linear light, both in [0, 1].
decode ∷ Double → Double
decode s = if s <= 0.04045 then s / 12.92 else ((s + 0.055) / 1.055) ** 2.4

-- | The sRGB transfer function's encoding direction.
encode ∷ Double → Double
encode l = if l <= 0.0031308 then l * 12.92 else 1.055 * l ** (1 / 2.4) - 0.055

-- | A clear colour, in linear light, of these sRGB bytes.
clearColourOf ∷ (Word8, Word8, Word8) → ClearColour
clearColourOf (r, g, b) = ClearColour (lin r) (lin g) (lin b) 1
  where
    lin byte = realToFrac (decode (fromIntegral byte / 255))

-- Readbacks and hand-stated expectations ------------------------------------------------------------------------------

-- | A readback: width, height and RGBA8 bytes, top row first.
data Readback = Readback
  { readbackWidth :: !Int
  , readbackHeight :: !Int
  , readbackBytes :: !ByteString
  }
  deriving (Eq, Show)

-- | The pixel at a column and row, or nothing outside the readback or when it is short.
pixelOf ∷ Readback → Int → Int → Maybe Texel
pixelOf (Readback width height bytes) x y =
  case readPixel R8G8B8A8Srgb (PixelExtent width height) bytes x y of
    Right (Rgba8 r g b a) → Just (r, g, b, a)
    Left _ → Nothing

-- | A position and the colour the specification puts there, each channel within a tolerance in code values.
data Named = Named
  { namedName :: !Text
  , namedX :: !Int
  , namedY :: !Int
  , namedWant :: !Texel
  , namedTolerance :: !Word8
  }
  deriving (Eq, Show)

-- | A named expectation the readback did not meet.
data Mismatch = Mismatch
  { mismatchName :: !Text
  , mismatchWanted :: !Texel
  , mismatchGot :: !(Maybe Texel)
  , mismatchTolerance :: !Word8
  }
  deriving (Eq, Show)

-- | The names whose pixel is not within tolerance of what was stated, or is not in the readback.
checkNamed ∷ Readback → [Named] → [Mismatch]
checkNamed readback = concatMap check
  where
    check (Named name x y want tolerance) = case pixelOf readback x y of
      Just got | near tolerance want got → []
      other → [Mismatch name want other tolerance]

near ∷ Word8 → Texel → Texel → Bool
near tolerance (a, b, c, d) (e, f, g, h) = and (zipWith close [a, b, c, d] [e, f, g, h])
  where
    close p q = abs (fromIntegral p - fromIntegral q ∷ Int) <= fromIntegral tolerance

showTexel ∷ Texel → Text
showTexel (r, g, b, a) = Text.pack (show (r, g, b, a))

-- Specifications ------------------------------------------------------------------------------------------------------

-- | One sprite of a case: a fixture drawn into a rectangle in logical pixels (x, y, width, height).
data Placement = Placement
  { placeFixture :: !Fixture
  , placeRect :: !(Float, Float, Float, Float)
  }

-- | A case as authored: the clear in sRGB bytes, the sprites in list order (later over earlier), the target's metrics
-- and the hand-stated expectations.
data CaseSpec = CaseSpec
  { specLabel :: !Text
  , specClear :: !(Word8, Word8, Word8)
  , specPlacements :: ![Placement]
  , specFramebuffer :: !(Int, Int)
  , specLogical :: !(Int, Int)
  , specScale :: !Float
  , specNamed :: ![Named]
  }

-- | The facts the display adapter supplies for the specification's target.
specFacts ∷ CaseSpec → FrameFacts
specFacts spec =
  FrameFacts
    { factsFramebuffer = (fromIntegral (fst (specFramebuffer spec)), fromIntegral (snd (specFramebuffer spec)))
    , factsLogical = Just (fromIntegral (fst (specLogical spec)), fromIntegral (snd (specLogical spec)))
    , factsScale = Just (specScale spec, specScale spec)
    }

-- | The metrics written out from the specification (not through the production derivation).
specMetrics ∷ CaseSpec → TargetMetrics
specMetrics spec =
  TargetMetrics
    (PixelExtent (fst (specLogical spec)) (snd (specLogical spec)))
    (PixelExtent (fst (specFramebuffer spec)) (snd (specFramebuffer spec)))
    (specScale spec)
    (specScale spec)

specClearColour ∷ CaseSpec → ClearColour
specClearColour = clearColourOf . specClear

-- | The handle the specification's i-th distinct fixture is given in the specification's own snapshot.
specHandle ∷ Int → Api.TextureHandle
specHandle index = fromBackendHandle (TextureHandle (fromIntegral index) 1)

-- | The distinct fixtures of a specification, in order of first use.
distinctFixtures ∷ CaseSpec → [Fixture]
distinctFixtures spec = go [] (map placeFixture (specPlacements spec))
  where
    go seen [] = reverse seen
    go seen (fixture : rest)
      | any ((== fixtureFile fixture) . fixtureFile) seen = go seen rest
      | otherwise = go (fixture : seen) rest

-- | The specification as a window-pass snapshot, written out here: one pass, cleared to the opaque colour, one
-- full-target view of the framebuffer with the approved settings written out, one UI layer listing the sprites in list
-- order, each placing the unit square at its rectangle, showing the whole image, with the neutral tint.
specSnapshot ∷ CaseSpec → Snapshot
specSnapshot spec = Snapshot [Pass WindowTarget (specClearColour spec) [view]]
  where
    (width, height) = specFramebuffer spec
    view =
      ViewWith
        { viewCamera = Camera (V2 0 0) 1 Nothing
        , viewViewport = Viewport (V2 0 0) (V2 (fromIntegral width) (fromIntegral height))
        , viewSettings = ViewSettings {settingUiScale = 1, settingPixelSnap = False, settingFilter = FilterNearest, settingBrightness = 1, settingZoomMode = PixelsPerUnit}
        , viewClips = []
        , viewMaterials = Map.empty
        , viewFrameTables = []
        , viewAnimationTime = 0
        , viewLayers = [UiLayer (map sprite (specPlacements spec))]
        }
    handles = Map.fromList (zip (map fixtureFile (distinctFixtures spec)) [0 ..])
    sprite (Placement fixture (x, y, w, h)) =
      Instance
        { instanceTransform = fromColumns (V2 w 0) (V2 0 h) (V2 x y)
        , instanceUv = UvRect 0 0 1 1
        , instanceTexture = specHandle (fromMaybe 0 (Map.lookup (fixtureFile fixture) handles))
        , instanceDepthKey = 0
        , instanceTint = Tint 255 255 255 255
        , instanceSampler = SamplerDefault
        , instanceTranslucent = False
        , instanceAdditive = False
        , instanceClip = 0
        , instanceFrameTable = 0
        , instanceParameter = 0
        , instanceMaterial = defaultMaterial
        }

-- | Which fixture each handle of the specification's own snapshot names.
specTextures ∷ CaseSpec → Api.TextureHandle → Maybe Fixture
specTextures spec handle = lookup handle [(specHandle index, fixture) | (index, fixture) ← zip [0 ..] (distinctFixtures spec)]

-- | Which fixture each handle of a candidate snapshot names, taking the candidate's instances in the order they are drawn
-- and the specification's placements in the order they were authored. An instance that is not the placement's would
-- not draw the placement's fixture, and the judges say so.
candidateTextures ∷ CaseSpec → Snapshot → Api.TextureHandle → Maybe Fixture
candidateTextures spec (Snapshot all') handle =
  lookup handle (zip [instanceTexture i | p ← all', v ← passViews p, l ← viewLayers v, i ← layerInstances l] (map placeFixture (specPlacements spec)))

-- | The oracle over a snapshot, for a window of these metrics, with these textures. The cutout marks are
-- the textures' own binary-alpha classification, as the registry's default mark is.
specOracle ∷ CaseSpec → TargetMetrics → ValidSnapshot → (Api.TextureHandle → Maybe DecodedImage) → CutoutMarks → Oracle
specOracle spec metrics valid textureOf marks =
  newOracle
    OracleInput
      { inputSnapshot = valid
      , inputCutoutMarks = marks
      , inputWindow = Just (TargetSpec metrics R8G8B8A8Srgb (PixelExtent (fst (specFramebuffer spec)) (snd (specFramebuffer spec))))
      , inputOffscreen = Map.empty
      , inputTextures = textureOf
      }

-- The comparator -------------------------------------------------------------------------------------------------------

-- | What the oracle made of every pixel of a readback.
data Judgement = Judgement
  { judgedDeterminate :: !Int
    -- ^ Pixels the oracle determined and the readback matched within the oracle's tolerance.
  , judgedFailed :: ![Text]
    -- ^ Pixels it determined and the readback did not match, and pixels the readback does not hold.
  , judgedIndeterminate :: ![(Text, Int)]
    -- ^ Pixels the oracle declined to determine, by reason, with how many.
  , judgedUnevaluable :: ![Text]
    -- ^ Pixels the oracle could not evaluate: an input defect, which fails the image.
  }
  deriving (Eq, Show)

-- | Judge every pixel of the readback against the oracle. An image passes when nothing failed, nothing was
-- unevaluable and at least one pixel was determinate; an indeterminate pixel counts for no success.
judgeWhole ∷ Oracle → Readback → Judgement
judgeWhole oracle (Readback width height bytes) =
  Judgement
    { judgedDeterminate = length [() | (_, Expected _ _, verdict) ← results, passes verdict]
    , judgedFailed = [describe at verdict | (at, Expected _ _, verdict) ← results, not (passes verdict)]
    , judgedIndeterminate = Map.toList (Map.fromListWith (+) [(reason why, 1) | (_, Indeterminate why, _) ← results])
    , judgedUnevaluable = [Text.pack (show at <> " " <> show why) | (at, Unevaluable why, _) ← results]
    }
  where
    results = [(at, expect oracle at, verdict) | y ← [0 .. height - 1], x ← [0 .. width - 1], let at = Probe 0 x y, let verdict = judgeReadback oracle at bytes]
    describe (Probe _ x y) verdict = "pixel (" <> Text.pack (show x) <> "," <> Text.pack (show y) <> ") " <> Text.pack (show (verdict ∷ Verdict))
    reason why = Text.pack (takeWhile (/= ' ') (show why))

-- | Whether an image passes: nothing failed, nothing was unevaluable and at least one pixel was determinate. An
-- indeterminate pixel counts for no success.
judgementOk ∷ Judgement → Bool
judgementOk j = null (judgedFailed j) && null (judgedUnevaluable j) && judgedDeterminate j > 0

-- | Where the oracle's own expectation disagrees with a hand-stated one: a named position the oracle declines to
-- determine, cannot evaluate, or puts outside the stated tolerance (the sum of the stated one and the oracle's).
agreesWith ∷ Oracle → [Named] → [Text]
agreesWith oracle = concatMap check
  where
    check (Named name x y want tolerance) = case expect oracle (Probe 0 x y) of
      Expected (Rgba8 r g b a) _ | near (tolerance + 1) want (r, g, b, a) → []
      Expected (Rgba8 r g b a) _ → [name <> ": the oracle expects " <> showTexel (r, g, b, a) <> ", the specification " <> showTexel want]
      Indeterminate why → [name <> ": the oracle declines to determine it: " <> Text.pack (show why)]
      Unevaluable why → [name <> ": the oracle cannot evaluate it: " <> Text.pack (show why)]

-- | The ways a candidate window-pass snapshot differs from the specification's, ignoring only which texture handle each
-- sprite names: a pass count, a clear colour beyond rounding, a view, a settings value or an instance that is not the
-- one the specification wrote.
translationDiffs ∷ Snapshot -> Snapshot -> [Text]
translationDiffs candidate wanted
  | length (snapshotPasses candidate) /= length (snapshotPasses wanted) = ["the pass counts differ"]
  | otherwise = concat (zipWith pass (snapshotPasses candidate) (snapshotPasses wanted))
  where
    neutral = specHandle 0
    pass p q =
      [ "the pass target differs" | passTarget p /= passTarget q ]
        <> [ "the clear colour differs: " <> Text.pack (show (passClear p)) <> " against " <> Text.pack (show (passClear q)) | not (clearsClose (passClear p) (passClear q)) ]
        <> [ "the views differ" | map plain (passViews p) /= map plain (passViews q) ]
    plain view = view {viewLayers = map layer (viewLayers view)}
    layer = \case
      UiLayerWith chunks instances → UiLayerWith chunks (map (\i → i {instanceTexture = neutral}) instances)
      WorldLayerWith depth chunks instances → WorldLayerWith depth chunks (map (\i → i {instanceTexture = neutral}) instances)
    clearsClose (ClearColour a b c d) (ClearColour e f g h) = and (zipWith (\p q → abs (p - q) < 1.0e-5) [a, b, c, d] [e, f, g, h])

-- | The same snapshot with its window pass drawing into this offscreen target instead: the one value the target
-- substitution changes. A pass that already drew into an offscreen target is left as it is.
retargeted ∷ TargetRef → Snapshot → Snapshot
retargeted reference (Snapshot all') = Snapshot [if passTarget p == WindowTarget then p {passTarget = OffscreenTarget reference} else p | p ← all']

-- | Whether two snapshots have the same passes, clears and views, differing at most in the targets the passes draw into.
sameExceptTarget ∷ Snapshot → Snapshot → Bool
sameExceptTarget (Snapshot a) (Snapshot b) = length a == length b && and (zipWith same a b)
  where
    same p q = passClear p == passClear q && passViews p == passViews q

