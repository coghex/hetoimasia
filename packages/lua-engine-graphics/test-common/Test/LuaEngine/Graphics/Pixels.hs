-- | The same grid scene viewed on a target of this framebuffer extent, logical extent and content scale: the sprite is
-- authored at logical (10, 8) with size 32 x 24, so a framebuffer a scale of s times the logical one has it at (10s, 8s)
-- with blocks of 8s pixels. A probe is stated only where the target holds the pixel.
gridAtScale ∷ Int → (Int, Int) → (Int, Int) → Text → CaseSpec
gridAtScale scale framebuffer logical label =
  CaseSpec label (20, 20, 40) [Placement gridFixture (10, 8, 32, 24)] framebuffer logical (fromIntegral scale)
    (filter inside (blocks <> corners <> outside <> boundaries))
  where
    (width, height) = framebuffer
    inside n = namedX n >= 0 && namedY n >= 0 && namedX n < width && namedY n < height
    grid = fixtureTexel gridFixture
    s = scale
    -- block (c, r), its middle: x = 10s + 8s c + 4s, y = 8s + 8s r + 4s
    blocks = [Named (name "block" c r) (10 * s + 8 * s * c + 4 * s) (8 * s + 8 * s * r + 4 * s) (grid c r) exact | r ← [0 .. 2], c ← [0 .. 3]]
